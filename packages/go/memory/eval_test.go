// TestEvaluation_EveryPromotionIsExplained checks the property that makes "why
// does it remember that about me" answerable: for every tier a record occupies,
// a stated rule explains it.
//
// It re-derives each decision from PromotionPolicy.Evaluate and compares
// against what the sweep actually did. A divergence would mean the sweep
// promotes for reasons the policy cannot explain.
func TestEvaluation_EveryPromotionIsExplained(t *testing.T) {
	c := newEvalCorpus(t)
	s2ReturningCaller(t, c, "subject-1")

	st := c.h.Assistant().Store
	pol := DefaultPromotionPolicy()

	// Read a subset repeatedly, which is what earns promotion.
	hot := st.Index().ByKind("subject-1", KindContact)
	c.h.Clock.Advance(10 * time.Second)
	for i := uint64(0); i < pol.AccessesToPromote; i++ {
		for _, k := range hot {
			if _, err := st.Retrieve(k, "evaluator"); err != nil {
				t.Fatal(err)
			}
		}
	}

	// Predict, then sweep, then compare.
	now := c.h.Clock.Now()
	predicted := 0
	for _, k := range st.Index().BySubject("subject-1") {
		r, ok := st.Index().Get(k)
		if !ok {
			continue
		}
		if pol.Evaluate(r, now) == TierPromoteUp {
			predicted++
		}
	}

	reports := c.h.Runtime.Sweep()
	promoted := 0
	for _, rep := range reports {
		promoted += rep.Promoted
	}

	tiers := map[Tier]int{}
	unexplained := 0
	for _, k := range st.Index().BySubject("subject-1") {
		r, ok := st.Index().Get(k)
		if !ok {
			continue
		}
		tiers[r.Tier]++
		// A record above the working tier must be there because it was pinned
		// at creation or because it earned promotion.
		if r.Tier > TierWorking && !r.Pinned && r.AccessCount < pol.AccessesToPromote {
			// Records are seeded at TierShortTerm, so this is only a finding
			// for anything that climbed further.
			if r.Tier > TierShortTerm {
				unexplained++
			}
		}
	}

	t.Logf("predicted promotions=%d actual=%d", predicted, promoted)
	t.Logf("tier distribution: working=%d short=%d long=%d",
		tiers[TierWorking], tiers[TierShortTerm], tiers[TierLongTerm])
	t.Logf("promotions with no explaining rule: %d", unexplained)

	if promoted != predicted {
		t.Errorf("sweep promoted %d records, the policy explains %d", promoted, predicted)
	}
	if unexplained != 0 {
		t.Errorf("%d records occupy a tier no rule explains", unexplained)
	}
}

// TestEvaluation_DerivedNeverClimbsToLongTerm measures the guard that stops the
// platform permanently remembering something a person never said.
func TestEvaluation_DerivedNeverClimbsToLongTerm(t *testing.T) {
	c := newEvalCorpus(t)
	st := c.h.Assistant().Store

	created := 0
	for i := 0; i < 4; i++ {
		r := InternalRecord("subject-1", KindUser, fmt.Sprintf("inferred-%d", i), "an inference")
		r.Provenance = Provenance{Source: "inference", Derived: true}
		c.put(t, NamespaceAssistant, r)
		created++
	}

	// Read them hard enough to earn promotion many times over.
	c.h.Clock.Advance(10 * time.Second)
	for round := 0; round < 10; round++ {
		for i := 0; i < 4; i++ {
			k := Key{Subject: "subject-1", Kind: KindUser, Name: fmt.Sprintf("inferred-%d", i)}
			if _, err := st.Retrieve(k, "evaluator"); err != nil {
				t.Fatal(err)
			}
		}
		c.h.Runtime.Sweep()
		c.h.Clock.Advance(10 * time.Second)
	}

	reachedLongTerm := 0
	for i := 0; i < 4; i++ {
		k := Key{Subject: "subject-1", Kind: KindUser, Name: fmt.Sprintf("inferred-%d", i)}
		r, ok := st.Index().Get(k)
		if !ok {
			continue
		}
		if r.Tier == TierLongTerm {
			reachedLongTerm++
		}
	}

	t.Logf("derived records created=%d reached long term=%d", created, reachedLongTerm)
	if reachedLongTerm != 0 {
		t.Errorf("%d derived records reached the long-term tier", reachedLongTerm)
	}
}

