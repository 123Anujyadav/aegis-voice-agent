// TestEvaluation_RecallIsTotal measures whether every stored, active, in-scope
// record is returned by a scoped query for it.
//
// It must be 100%. This is an exact-match index, not a ranking system, so a
// miss here is an index bug rather than a quality shortfall — which is exactly
// what makes the number valuable as a regression guard and uninteresting on its
// own.
func TestEvaluation_RecallIsTotal(t *testing.T) {
	cases := []struct {
		name  string
		ns    Namespace
		build func(*testing.T, *evalCorpus, SubjectID)
	}{
		{"S1 single call", NamespaceAssistant, s1SingleCall},
		{"S2 returning caller", NamespaceAssistant, s2ReturningCaller},
		{"S3 business", NamespaceReceptionist, s3Business},
	}

	for _, tc := range cases {
		c := newEvalCorpus(t)
		tc.build(t, c, "subject-1")

		res, err := c.h.Bundle(tc.ns).Retriever.Search(Query{
			Subject:        "subject-1",
			MaxSensitivity: Internal,
			Limit:          1000,
		}, "evaluator")
		if err != nil {
			t.Fatalf("%s: search: %v", tc.name, err)
		}

		recalled := len(res.Records)
		t.Logf("%-22s stored=%d recalled=%d recall=%.1f%%",
			tc.name, c.stored, recalled, 100*float64(recalled)/float64(c.stored))

		if recalled != c.stored {
			t.Errorf("%s: recalled %d of %d stored records", tc.name, recalled, c.stored)
		}
	}
}

