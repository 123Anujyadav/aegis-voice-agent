// TestEvaluation_IdenticalInputsProduceIdenticalMemory runs the same corpus
// through the same operations repeatedly and counts divergences.
//
// A memory system that produces different results on identical inputs cannot be
// debugged from a bug report, cannot be audited, and cannot answer a regulator
// asking what it held on a given date.
func TestEvaluation_IdenticalInputsProduceIdenticalMemory(t *testing.T) {
	const runs = 25

	fingerprint := func() (string, string, string) {
		c := newEvalCorpus(t)
		s2ReturningCaller(t, c, "subject-1")
		st := c.h.Assistant().Store

		c.h.Clock.Advance(10 * time.Second)
		for _, k := range st.Index().ByKind("subject-1", KindContact) {
			for i := 0; i < 3; i++ {
				_, _ = st.Retrieve(k, "evaluator")
			}
		}

		reports := c.h.Runtime.Sweep()
		sweep := fmt.Sprint(reports)

		res, err := c.h.Assistant().Retriever.Search(Query{
			Subject: "subject-1", MaxSensitivity: Internal, Limit: 50,
		}, "evaluator")
		if err != nil {
			t.Fatal(err)
		}
		var search string
		for _, r := range res.Records {
			search += r.Key.String() + ";"
		}

		ctx, err := c.h.Assistant().Context.Build(ContextRequest{
			Subject: "subject-1", MaxSensitivity: Internal,
			Budget: TokenBudget{MaxTokens: 2048}, Actor: "evaluator",
		})
		if err != nil {
			t.Fatal(err)
		}
		var context string
		for _, sl := range ctx.Slices {
			context += sl.Scope.String() + ":"
			for _, r := range sl.Records {
				context += r.Key.Name + ","
			}
		}
		return sweep, search, context
	}

	sweep0, search0, ctx0 := fingerprint()
	sweepDiv, searchDiv, ctxDiv := 0, 0, 0
	for i := 1; i < runs; i++ {
		s, q, c := fingerprint()
		if s != sweep0 {
			sweepDiv++
		}
		if q != search0 {
			searchDiv++
		}
		if c != ctx0 {
			ctxDiv++
		}
	}

	t.Logf("runs=%d sweep divergences=%d search divergences=%d context divergences=%d",
		runs, sweepDiv, searchDiv, ctxDiv)

	if sweepDiv+searchDiv+ctxDiv != 0 {
		t.Errorf("determinism broken: sweep=%d search=%d context=%d",
			sweepDiv, searchDiv, ctxDiv)
	}
}
