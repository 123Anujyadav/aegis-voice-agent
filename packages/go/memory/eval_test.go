// TestEvaluation_ScopeNeverLeaks probes every boundary the engine claims to
// enforce and counts how many records cross it. Zero is the only passing
// number: a scoping mechanism that leaks 1% is not a scoping mechanism.
func TestEvaluation_ScopeNeverLeaks(t *testing.T) {
	c := newEvalCorpus(t)
	c.h.Grant("subject-a", "consent-a")

	s1SingleCall(t, c, "subject-a")
	s1SingleCall(t, c, "subject-b")
	c.put(t, NamespaceFraud, InternalRecord("subject-a", KindUser, "risk-signal", "elevated"))
	c.put(t, NamespaceAssistant, PersonalRecord("subject-a", KindUser, "personal-note",
		"personal content", "consent-a"))
	c.put(t, NamespaceAssistant, WithAttributes(
		InternalRecord("subject-a", KindConversation, "other-conv-turn", "dialogue"),
		map[string]string{AttrConversation: "conv-2"}))

	// A non-active record, to prove no query serves one.
	expired := c.put(t, NamespaceAssistant, NewScratchpad("subject-a", "gone",
		Value{ContentType: "text/plain", Data: []byte("x")}))
	if err := c.h.Assistant().Store.Expire(expired); err != nil {
		t.Fatal(err)
	}

	assistant := c.h.Assistant().Retriever

	probes := []struct {
		name  string
		query Query
		leak  func(*Record) bool
	}{
		{
			"subject A query returns subject B",
			Query{Subject: "subject-a", MaxSensitivity: Internal, Limit: 1000},
			func(r *Record) bool { return r.Key.Subject != "subject-a" },
		},
		{
			"conversation 1 query returns conversation 2",
			Query{Subject: "subject-a", Attribute: AttrConversation, Value: "conv-1",
				MaxSensitivity: Internal, Limit: 1000},
			func(r *Record) bool { return r.Value.Attributes[AttrConversation] != "conv-1" },
		},
		{
			"Internal ceiling returns Personal",
			Query{Subject: "subject-a", MaxSensitivity: Internal, Limit: 1000},
			func(r *Record) bool { return r.Sensitivity > Internal },
		},
		{
			"active query returns non-active records",
			Query{Subject: "subject-a", MaxSensitivity: Internal, Limit: 1000},
			func(r *Record) bool { return r.State != StateActive },
		},
	}

	total := 0
	for _, p := range probes {
		res, err := assistant.Search(p.query, "evaluator")
		if err != nil {
			t.Fatalf("%s: %v", p.name, err)
		}
		leaks := 0
		for _, r := range res.Records {
			if p.leak(r) {
				leaks++
			}
		}
		total += leaks
		t.Logf("%-48s returned=%3d leaks=%d", p.name, len(res.Records), leaks)
		if leaks != 0 {
			t.Errorf("%s: %d records crossed the boundary", p.name, leaks)
		}
	}

	// Namespace isolation is structural, so it is probed by key rather than by
	// query: the fraud record simply is not in the assistant's store.
	fraudKey := Key{Subject: "subject-a", Kind: KindUser, Name: "risk-signal"}
	if _, err := c.h.Assistant().Store.Retrieve(fraudKey, "evaluator"); err == nil {
		total++
		t.Error("fraud namespace record was readable from the assistant namespace")
	}
	t.Logf("%-48s leaks=%d", "assistant reads fraud namespace by key", 0)
	t.Logf("TOTAL LEAKS ACROSS ALL PROBES: %d", total)
}

