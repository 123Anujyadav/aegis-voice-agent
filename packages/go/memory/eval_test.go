// Evaluation harness for docs/memory/MEMORY_EVALUATION.md.
//
// The other suites answer "is this built correctly". These answer a different
// question: does the engine remember and forget the RIGHT things? They build
// named corpora, measure a property over each, and print the number that goes
// into the report. Every figure in MEMORY_EVALUATION.md comes from here, so a
// change that degrades recall or leaks a scope shows up as a changed number
// rather than as a document nobody reprinted.
//
// They assert as well as measure. A report generated by a suite that cannot
// fail is a press release.

// evalCorpus builds a scenario and reports what it stored.
type evalCorpus struct {
	h      *Harness
	stored int
}

func newEvalCorpus(t *testing.T) *evalCorpus {
	t.Helper()
	h, err := NewHarness()
	if err != nil {
		t.Fatal(err)
	}
	return &evalCorpus{h: h}
}

func (c *evalCorpus) put(t *testing.T, ns Namespace, r *Record) Key {
	t.Helper()
	if r.Provenance.Source == "" {
		r.Provenance.Source = "evaluation-corpus"
	}
	stored, err := c.h.Bundle(ns).Store.Store(r)
	if err != nil {
		t.Fatalf("store %v: %v", r.Key, err)
	}
	c.stored++
	c.h.Clock.Advance(time.Millisecond)
	return stored.Key
}

// s1SingleCall is one screening call: a conversation, the preferences that
// shape it and the policy that bounds it.
func s1SingleCall(t *testing.T, c *evalCorpus, subject SubjectID) {
	t.Helper()
	c.put(t, NamespaceAssistant, NewPolicy(subject, "call-limits",
		Value{ContentType: "text/plain", Data: []byte("max_duration=180s")}))
	for i, name := range []string{"language", "greeting", "callback-window"} {
		c.put(t, NamespaceAssistant, NewPreference(subject, name,
			Value{ContentType: "text/plain", Data: []byte(fmt.Sprintf("value-%d", i))}, Internal))
	}
	for i := 0; i < 24; i++ {
		c.put(t, NamespaceAssistant, WithAttributes(
			InternalRecord(subject, KindConversation, fmt.Sprintf("turn-%02d", i),
				"a turn of dialogue with some length to it"),
			map[string]string{AttrConversation: "conv-1"}))
	}
}

// s2ReturningCaller is five conversations over thirty days plus the contact
// graph and preferences a returning caller accumulates.
func s2ReturningCaller(t *testing.T, c *evalCorpus, subject SubjectID) {
	t.Helper()
	for i := 0; i < 8; i++ {
		c.put(t, NamespaceAssistant, NewPreference(subject, fmt.Sprintf("pref-%d", i),
			Value{ContentType: "text/plain", Data: []byte("v")}, Internal))
	}
	for conv := 0; conv < 5; conv++ {
		for i := 0; i < 4; i++ {
			c.put(t, NamespaceAssistant, WithAttributes(
				InternalRecord(subject, KindConversation,
					fmt.Sprintf("c%d-turn-%d", conv, i), "dialogue"),
				map[string]string{AttrConversation: fmt.Sprintf("conv-%d", conv)}))
		}
		c.h.Clock.Advance(6 * 24 * time.Hour)
	}
	for i := 0; i < 12; i++ {
		c.put(t, NamespaceAssistant, WithAttributes(
			InternalRecord(subject, KindContact, fmt.Sprintf("contact-%02d", i), "caller record"),
			map[string]string{AttrContact: fmt.Sprintf("contact-%02d", i)}))
	}
}

// s3Business is a receptionist's corpus: business configuration, policies and
