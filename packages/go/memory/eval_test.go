// TestEvaluation_RetentionIsNeverEarly measures expiry error against each
// retention class. The error must always be late, never early: retention is a
// maximum, so overshooting by up to one sweep interval is correct and
// undershooting by anything is data destroyed before it was allowed to be.
func TestEvaluation_RetentionIsNeverEarly(t *testing.T) {
	cases := []struct {
		name string
		ret  Retention
	}{
		{"short", RetentionShort},
		{"standard", RetentionStandard},
		{"legal hold", RetentionLegalHold},
	}

	for _, tc := range cases {
		c := newEvalCorpus(t)
		st := c.h.Assistant().Store

		r := InternalRecord("subject-1", KindUser, "held", "payload")
		r.Retention = tc.ret
		r.Pinned = false
		k := c.put(t, NamespaceAssistant, r)

		stored, ok := st.Index().Get(k)
		if !ok {
			t.Fatalf("%s: record vanished", tc.name)
		}

		if tc.ret == RetentionLegalHold {
			// Advance far past any other class and confirm it holds. The read
			// keeps it out of the idleness path, so what is measured is
			// retention rather than disuse.
			c.h.Clock.Advance(365 * 24 * time.Hour)
			if _, err := st.Retrieve(k, "evaluator"); err != nil {
				t.Fatalf("legal hold: %v", err)
			}
			c.h.Runtime.Sweep()
			after, _ := st.Index().Get(k)
			t.Logf("%-12s configured=never    expires_at=zero(%v) state after 365d=%v",
				tc.name, stored.ExpiresAt.IsZero(), after.State)
			if after.State != StateActive {
				t.Error("legal hold expired after 365 days")
			}
			continue
		}

		// The horizon the engine actually computed, rather than one this test
		// asserts independently — the record is the source of truth for when
		// it expires.
		d := stored.ExpiresAt.Sub(stored.CreatedAt)
		if d <= 0 {
			t.Fatalf("%s: no expiry horizon was set", tc.name)
		}

		// A read before each sweep resets idleness, so the only thing that can
		// expire this record is its retention horizon. Without it the sweep's
		// idle-demotion path would expire the record for an unrelated reason
		// and the measurement would be of disuse, not retention.
		c.h.Clock.Advance(d - time.Second)
		if _, err := st.Retrieve(k, "evaluator"); err != nil {
			t.Fatalf("%s: before horizon: %v", tc.name, err)
		}
		c.h.Runtime.Sweep()
		early, _ := st.Index().Get(k)
		earlyExpiry := early.State != StateActive

		// Past the horizon: must expire within one sweep.
		c.h.Clock.Advance(2 * time.Second)
		c.h.Runtime.Sweep()
		late, _ := st.Index().Get(k)

		t.Logf("%-12s configured=%-9s early=%v state_after=%v",
			tc.name, d, earlyExpiry, late.State)

		if earlyExpiry {
			t.Errorf("%s: record expired BEFORE its retention horizon", tc.name)
		}
		if late.State == StateActive {
			t.Errorf("%s: record still active past its retention horizon", tc.name)
		}
	}
}

// ---------------------------------------------------------------------------
// E6 · Context quality under budget pressure
// ---------------------------------------------------------------------------

// TestEvaluation_ContextKeepsWhatMatters starves the context builder and
// records which scopes survive.
//
// The measured property is not "how much fitted" but "was the right thing
// dropped". An assistant that forgets an operating limit is dangerous; one that
// forgets a preference is rude; one that forgets the last few turns is merely
// forgetful. Under pressure the forgetful failure must be the one chosen.
func TestEvaluation_ContextKeepsWhatMatters(t *testing.T) {
	c := newEvalCorpus(t)
	s3Business(t, c, "biz-subject")
	b := c.h.Bundle(NamespaceReceptionist)

	// First measure demand with an effectively unbounded budget.
	full, err := b.Context.Build(ContextRequest{
		Subject: "biz-subject", MaxSensitivity: Internal,
		Budget: TokenBudget{MaxTokens: 1 << 20}, Actor: "evaluator",
	})
	if err != nil {
		t.Fatal(err)
	}
	demand := full.TotalTokens
	budget := demand / 4

	tight, err := b.Context.Build(ContextRequest{
		Subject: "biz-subject", MaxSensitivity: Internal,
		Budget: TokenBudget{MaxTokens: budget}, Actor: "evaluator",
	})
	if err != nil {
		t.Fatal(err)
	}

	t.Logf("demand=%d tokens  budget=%d tokens (25%%)  used=%d  unused=%d",
		demand, budget, tight.TotalTokens, budget-tight.TotalTokens)
	for _, sl := range tight.Slices {
		t.Logf("  kept    %-14s records=%2d tokens=%4d truncated=%v",
			sl.Scope, len(sl.Records), sl.Tokens, sl.Truncated)
	}
	for _, s := range tight.Dropped {
		t.Logf("  dropped %-14s", s)
	}

	if tight.TotalTokens > budget {
		t.Errorf("context of %d tokens exceeded its %d budget", tight.TotalTokens, budget)
	}

	// The runtime scope carries operating limits. It is priority zero and must
	// survive any budget that can hold it at all.
	if _, ok := tight.Slice(ScopeRuntime); !ok {
		t.Error("runtime scope (operating limits) was dropped under pressure")
	}
	for _, s := range tight.Dropped {
		if s == ScopeRuntime {
			t.Error("runtime scope was dropped while lower-priority scopes were kept")
		}
	}

	// High-priority scopes must be whole. A truncated preference list is a
	// context that is confidently wrong about the subject, which is worse than
	// one that is visibly short of history.
	for _, sl := range tight.Slices {
		if sl.Truncated && (sl.Scope == ScopeRuntime || sl.Scope == ScopePersonal) {
			t.Errorf("%s scope was truncated to %d of %d records under pressure",
				sl.Scope, len(sl.Records), sl.Available)
		}
	}

	// Truncation is permitted, silence about it is not. Every cut scope must
	// state how many records it could have carried, so a caller can tell a
	// short context from a complete one.
	for _, sl := range tight.Slices {
		if sl.Truncated && sl.Available <= len(sl.Records) {
			t.Errorf("%s scope reports truncation but claims Available=%d for %d records",
				sl.Scope, sl.Available, len(sl.Records))
		}
	}
}

