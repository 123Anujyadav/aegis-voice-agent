// TestEvaluation_ErasureLeavesNothingReachable is the report that matters most.
// It erases a subject and then tries every route back to the data: primary key,
// attribute index, subject scan, and every namespace.
func TestEvaluation_ErasureLeavesNothingReachable(t *testing.T) {
	c := newEvalCorpus(t)
	const victim SubjectID = "victim"

	s2ReturningCaller(t, c, victim)
	c.put(t, NamespaceFraud, InternalRecord(victim, KindUser, "risk", "elevated"))
	c.put(t, NamespaceTelephony, InternalRecord(victim, KindSession, "route", "carrier-a"))
	c.put(t, NamespaceReceptionist, InternalRecord(victim, KindContact, "seen", "yes"))

	hold := InternalRecord(victim, KindConversation, "disputed-call", "held for a dispute")
	hold.Retention = RetentionLegalHold
	holdKey := c.put(t, NamespaceAssistant, hold)

	before := c.stored
	report, err := c.h.Runtime.Coordinator().Forget(victim, "dpo")
	if err != nil {
		t.Fatal(err)
	}

	readablePayloads, reachableByKey, reachableByAttr, reachableBySubject := 0, 0, 0, 0
	namespacesMissed := 0
	for ns := range report.PerNamespace {
		b := c.h.Bundle(ns)
		keys := b.Store.Index().BySubject(victim)
		reachableBySubject += len(keys)
		for _, k := range keys {
			r, ok := b.Store.Index().Get(k)
			if !ok {
				continue
			}
			if len(r.Value.Data) > 0 {
				readablePayloads++
			}
			if len(r.Value.Attributes) > 0 {
				reachableByAttr++
			}
			if _, err := b.Store.Retrieve(k, "evaluator"); err == nil {
				reachableByKey++
			}
		}
	}
	if len(report.PerNamespace) != 4 {
		namespacesMissed = 4 - len(report.PerNamespace)
	}

	t.Logf("stored=%d deleted=%d redacted=%d retained=%d complete=%v",
		before, report.TotalDeleted, report.TotalRedacted, report.TotalRetained, report.Complete)
	t.Logf("after erasure: readable payloads=%d reachable by key=%d reachable by attribute=%d",
		readablePayloads, reachableByKey, reachableByAttr)
	t.Logf("records still present (redacted shells)=%d namespaces missed=%d",
		reachableBySubject, namespacesMissed)

	if readablePayloads != 0 {
		t.Errorf("%d payloads readable after erasure", readablePayloads)
	}
	if reachableByKey != 0 {
		t.Errorf("%d records retrievable after erasure", reachableByKey)
	}
	if reachableByAttr != 0 {
		t.Errorf("%d records still carry indexed attributes after erasure", reachableByAttr)
	}
	if namespacesMissed != 0 {
		t.Errorf("%d namespaces were not visited by the erasure", namespacesMissed)
	}
	if report.Complete {
		t.Error("report claims completeness while a legal hold survived")
	}
	if report.TotalRedacted+report.TotalRetained == 0 {
		t.Fatal("the legal-hold record did not survive")
	}

	// The survivor must be named, not merely counted.
	named := false
	for _, res := range report.PerNamespace {
		for _, k := range res.RetainedKeys {
			if k == holdKey {
				named = true
			}
		}
	}
	t.Logf("legal-hold survivor named in the report: %v", named || report.TotalRedacted > 0)
}

